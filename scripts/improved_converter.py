def detect_traditional_chars(text):
    """
    检测文本中是否包含繁体字
    """
    # 繁体字 Unicode 范围
    traditional_ranges = [
        (0x4E00, 0x9FFF),   # 基本汉字
        (0x3400, 0x4DBF),   # 扩展A
        (0x20000, 0x2A6DF), # 扩展B
        (0x2A700, 0x2B73F), # 扩展C
        (0x2B740, 0x2B81F), # 扩展D
        (0x2B820, 0x2CEAF), # 扩展E
        (0x2CEB0, 0x2EBEF)  # 扩展F
    ]

    traditional_chars = []
    for char in text:
        for start, end in traditional_ranges:
            if start <= ord(char) <= end:
                traditional_chars.append(char)
                break

    return list(set(traditional_chars))  # 去重

